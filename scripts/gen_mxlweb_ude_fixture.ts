// Export mxlweb's showcase/ude model with mxlweb-core and evaluate its
// derivatives at a few states: the fixture of MxlPy's nn_blocks import test
// (tests/assets/mxlweb_showcase_ude.fixture.json).
//
// Run from pages/mxl-web of the meta-repo (its mxlweb-core):
//   npx tsx ../../pkg-py/MxlPy/scripts/gen_mxlweb_ude_fixture.ts \
//     ../../pkg-py/MxlPy/tests/assets/mxlweb_showcase_ude.fixture.json
import { writeFileSync } from "node:fs";
import { initModel } from "../../../pages/mxl-web/src/routes/showcase/ude/model.ts";

// mxl-schemas ADR 0011 renumbered the format without changing it
const RENUMBERED: Record<string, string> = {
  "1.0": "0.1",
  "1.1": "0.2",
  "1.2": "0.3",
  "1.3": "0.4",
};

const out = process.argv[2];
const m = initModel();
const doc = JSON.parse(m.buildMxlJson("showcase_ude", "mxlweb showcase/ude"));
doc.spec_version = RENUMBERED[doc.spec_version] ?? doc.spec_version;
doc.$schema = doc.$schema.replace("/v1/", "/v0/");
const weights = JSON.parse(m.buildNNWeightsFile("ude_correction"));
const rhs = new Function(`return ${m.buildJs()}`)();
const pars = m.resolveAllAddressableValues();
const states = [
  [10, 10],
  [5, 2],
  [1, 15],
  [20, 0.5],
];
const derivatives = states.map((y) => rhs(0, y, pars));
writeFileSync(
  out,
  JSON.stringify(
    {
      note: "Generated by scripts/gen_mxlweb_ude_fixture.ts (mxlweb showcase/ude exported and evaluated with mxlweb-core).",
      doc,
      weights,
      states,
      derivatives,
      names: m.getAllAddressableNames(),
    },
    null,
    2,
  ) + "\n",
);
